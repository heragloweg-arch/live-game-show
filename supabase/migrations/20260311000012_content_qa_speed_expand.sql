ALTER TABLE public.challenges
  ADD COLUMN IF NOT EXISTS qa_status TEXT NOT NULL DEFAULT 'approved'
    CHECK (qa_status IN ('approved', 'flagged', 'rejected', 'needs_review'));

ALTER TABLE public.challenges
  ADD COLUMN IF NOT EXISTS qa_notes TEXT;

CREATE INDEX IF NOT EXISTS idx_challenges_qa ON public.challenges(qa_status) WHERE active = true;

-- ─── Deactivate / flag ambiguous or unsuitable prompts ───────
UPDATE public.challenges SET
  active = false,
  qa_status = 'rejected',
  qa_notes = 'Ambiguous / contested (Nile length depends on measurement)'
WHERE prompt LIKE '%أطول نهر في العالم%';

UPDATE public.challenges SET
  active = false,
  qa_status = 'rejected',
  qa_notes = 'Ill-formed prompt'
WHERE prompt LIKE '%الدولة العربية الوحيدة في أمريكا الجنوبية%';

UPDATE public.challenges SET
  active = false,
  qa_status = 'rejected',
  qa_notes = 'Not suitable as MCQ trivia about the Prophet'
WHERE prompt LIKE '%من هو النبي محمد%';

-- Soft-flag religion items that are too broad for timed MCQ (keep but mark)
UPDATE public.challenges SET
  qa_status = 'needs_review',
  qa_notes = 'Review tone/clarity for timed quiz'
WHERE type = 'knowledge' AND subtype = 'religion' AND qa_status = 'approved';

-- ─── Deduplicate exact same prompt (keep oldest) ─────────────
WITH ranked AS (
  SELECT id, prompt,
         ROW_NUMBER() OVER (PARTITION BY trim(prompt) ORDER BY created_at ASC NULLS LAST, id ASC) AS rn
  FROM public.challenges
  WHERE active = true
)
UPDATE public.challenges c SET
  active = false,
  qa_status = 'rejected',
  qa_notes = 'Duplicate prompt'
FROM ranked r
WHERE c.id = r.id AND r.rn > 1;

-- ─── Nile Africa — clearer prompt (keep African Nile) ────────
UPDATE public.challenges SET
  prompt = 'ما أطول نهر في أفريقيا؟',
  qa_status = 'approved',
  qa_notes = 'Clarified to Africa scope'
WHERE prompt LIKE '%أطول نهر في أفريقيا%';

